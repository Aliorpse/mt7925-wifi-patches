#!/usr/bin/env bash

set -Eeuo pipefail

readonly PROJECT='mt7925-wifi-patches'
readonly GENERATED='# Generated by mt7925-wifi-patches'
readonly -a MODULES=(mt76 mt76_connac_lib mt792x_lib mt7925_common mt7925e)
readonly -a MODULE_FILES=(mt76.ko mt76-connac-lib.ko mt792x-lib.ko mt7925-common.ko mt7925e.ko)
readonly -a UNLOAD_ORDER=(mt7925e mt7925_common mt792x_lib mt76_connac_lib mt76)

MODULES_ROOT=${MT7925_MODULES_ROOT:-/lib/modules}
ETC_ROOT=${MT7925_ETC_ROOT:-/etc}
PROC_MODULES=${MT7925_PROC_MODULES:-/proc/modules}
MODPROBE=${MT7925_MODPROBE:-modprobe}
DEPMOD=${MT7925_DEPMOD:-depmod}
MODINFO=${MT7925_MODINFO:-modinfo}
IW=${MT7925_IW:-iw}

KVER=''
KERNEL_ROOT=''
UPDATES=''
ACTIVE=''
NEW=''
PREVIOUS=''
SETTINGS_TMP=''
ASPM_TARGET=''
DISPATCHER_TARGET=''
ASPM_DESIRED=''
DISPATCHER_DESIRED=''
ASPM_EXPECTED=''
DISPATCHER_EXPECTED=''
aspm_backed_up=0
aspm_installed=0
dispatcher_backed_up=0
dispatcher_installed=0
preserve_settings_tmp=0
transaction_started=0
previous_moved=0
new_active=0
committed=0
RESOLUTION_ERROR=''
LOADED_ERROR=''

usage() {
    printf 'usage: %s install STAGE_DIR KVER DISABLE_ASPM DISABLE_POWER_SAVE\n' "${0##*/}" >&2
    printf '       %s revert KVER\n' "${0##*/}" >&2
}

die() {
    printf '%s: %s\n' "${0##*/}" "$*" >&2
    exit 1
}

warn() {
    printf '%s: rollback warning: %s\n' "${0##*/}" "$*" >&2
}

module_loaded() {
    local wanted=$1 name rest

    while read -r name rest; do
        [[ $name != "$wanted" ]] || return 0
    done < "$PROC_MODULES"
    return 1
}

unload_stack() {
    local module

    for module in "${UNLOAD_ORDER[@]}"; do
        if module_loaded "$module"; then
            "$MODPROBE" -r "$module"
        fi
    done
}

unload_stack_for_rollback() {
    local module

    for module in "${UNLOAD_ORDER[@]}"; do
        if module_loaded "$module" && ! "$MODPROBE" -r "$module"; then
            warn "could not unload $module"
        fi
    done
}

check_loaded_stack() {
    local module failed=0

    LOADED_ERROR=''
    for module in "${MODULES[@]}"; do
        if ! module_loaded "$module"; then
            [[ -n $LOADED_ERROR ]] || LOADED_ERROR="$module is not loaded"
            failed=1
        fi
    done
    return "$failed"
}

verify_loaded_stack() {
    check_loaded_stack || die "$LOADED_ERROR"
}

check_overlay_resolution() {
    local index resolved expected failed=0

    RESOLUTION_ERROR=''
    for index in "${!MODULES[@]}"; do
        expected="$ACTIVE/${MODULE_FILES[$index]}"
        if ! resolved=$("$MODINFO" -k "$KVER" -n "${MODULES[$index]}"); then
            [[ -n $RESOLUTION_ERROR ]] || RESOLUTION_ERROR="could not resolve ${MODULES[$index]}"
            failed=1
        elif [[ $resolved != "$expected" ]]; then
            [[ -n $RESOLUTION_ERROR ]] ||
                RESOLUTION_ERROR="${MODULES[$index]} resolves outside the active overlay: $resolved"
            failed=1
        fi
    done
    return "$failed"
}

verify_overlay_resolution() {
    check_overlay_resolution || die "$RESOLUTION_ERROR"
}

check_stock_resolution() {
    local module resolved failed=0

    RESOLUTION_ERROR=''
    for module in "${MODULES[@]}"; do
        if ! resolved=$("$MODINFO" -k "$KVER" -n "$module"); then
            [[ -n $RESOLUTION_ERROR ]] || RESOLUTION_ERROR="could not resolve $module"
            failed=1
        elif [[ $resolved != "$KERNEL_ROOT/kernel/"* ]]; then
            [[ -n $RESOLUTION_ERROR ]] || RESOLUTION_ERROR="$module does not resolve to a stock module: $resolved"
            failed=1
        fi
    done
    return "$failed"
}

verify_stock_resolution() {
    check_stock_resolution || die "$RESOLUTION_ERROR"
}

matches_generated() {
    local file=$1 expected=$2

    [[ -f $file && ! -L $file && -n $expected && -f $expected ]] || return 1
    cmp -s "$file" "$expected"
}

restore_setting() {
    local target=$1 expected=$2 installed=$3 backed_up=$4 name=$5
    local backup="$SETTINGS_TMP/$name.previous" recovery

    if ((installed)); then
        if matches_generated "$target" "$expected"; then
            rm -f "$target"
        else
            if ((backed_up)); then
                preserve_settings_tmp=1
                printf -v recovery 'diff -u -- %q %q' "$backup" "$target"
                warn "live setting preserved at $target; previous backup preserved at $backup; compare with: $recovery; restore the backup manually after review"
            else
                warn "live setting preserved at $target; no previous backup exists"
            fi
            return 0
        fi
    fi
    if ((backed_up)); then
        if ! mv "$backup" "$target"; then
            preserve_settings_tmp=1
            printf -v recovery 'mv -- %q %q' "$backup" "$target"
            warn "could not restore $target; backup preserved at $backup; restore it manually with: $recovery"
        fi
    fi
}

restore_settings() {
    restore_setting "$ASPM_TARGET" "$ASPM_EXPECTED" "$aspm_installed" "$aspm_backed_up" aspm
    restore_setting "$DISPATCHER_TARGET" "$DISPATCHER_EXPECTED" \
        "$dispatcher_installed" "$dispatcher_backed_up" dispatcher
}

rollback() {
    unload_stack_for_rollback
    restore_settings

    if ((new_active)); then
        rm -rf "$ACTIVE" || warn "could not remove failed overlay $ACTIVE"
    fi
    if ((previous_moved)); then
        mv "$PREVIOUS" "$ACTIVE" || warn "could not restore previous overlay"
    fi
    rm -rf "$NEW"

    if ! "$DEPMOD" -a "$KVER"; then
        warn "depmod failed for $KVER"
    fi
    if ! "$MODPROBE" mt7925e; then
        warn 'could not reload mt7925e'
    fi
    if [[ -d $ACTIVE ]]; then
        check_overlay_resolution || warn "rollback module resolution verification failed: $RESOLUTION_ERROR"
    else
        check_stock_resolution || warn "rollback module resolution verification failed: $RESOLUTION_ERROR"
    fi
    check_loaded_stack || warn "rollback loaded module verification failed: $LOADED_ERROR"
}

finish() {
    local status=$?

    trap - EXIT
    set +e
    if ((status != 0 && transaction_started && !committed)); then
        rollback
    fi
    [[ -z $NEW ]] || rm -rf "$NEW"
    if [[ -n $SETTINGS_TMP ]] && ((preserve_settings_tmp == 0)); then
        rm -rf "$SETTINGS_TMP"
    fi
    exit "$status"
}
trap finish EXIT

require_safe_roots() {
    local test_roots=0 root

    if [[ ${MT7925_MODULES_ROOT+x} || ${MT7925_ETC_ROOT+x} || ${MT7925_PROC_MODULES+x} ]]; then
        [[ ${MT7925_MODULES_ROOT-} && ${MT7925_ETC_ROOT-} && ${MT7925_PROC_MODULES-} ]] ||
            die 'test roots must set MT7925_MODULES_ROOT, MT7925_ETC_ROOT, and MT7925_PROC_MODULES together'
        [[ $MODULES_ROOT != /lib/modules && $ETC_ROOT != /etc && $PROC_MODULES != /proc/modules ]] ||
            die 'test roots must not name production paths'
        test_roots=1
    fi

    if ((EUID != 0 && !test_roots)); then
        die 'root privileges are required'
    fi
    for root in "$MODULES_ROOT" "$ETC_ROOT" "$PROC_MODULES"; do
        [[ $root == /* ]] || die "path must be absolute: $root"
    done
}

resolve_command() {
    local variable=$1 value=$2 resolved

    resolved=$(command -v "$value") || die "required command not found: $value"
    printf -v "$variable" '%s' "$resolved"
}

set_kernel_paths() {
    local kver=$1

    [[ $kver =~ ^[A-Za-z0-9._+-]+$ && $kver != . && $kver != .. ]] ||
        die "invalid kernel release: $kver"
    KVER=$kver
    KERNEL_ROOT="$MODULES_ROOT/$KVER"
    [[ -d $KERNEL_ROOT/kernel && ! -L $KERNEL_ROOT ]] ||
        die "kernel module tree not found: $KERNEL_ROOT/kernel"
    [[ -r $PROC_MODULES ]] || die "module state is not readable: $PROC_MODULES"

    UPDATES="$KERNEL_ROOT/updates"
    if [[ -e $UPDATES ]]; then
        [[ -d $UPDATES && ! -L $UPDATES ]] || die "unsafe updates directory: $UPDATES"
    fi
    ACTIVE="$UPDATES/$PROJECT"
    NEW="$UPDATES/.$PROJECT.new"
    PREVIOUS="$UPDATES/.$PROJECT.previous"
    for path in "$ACTIVE" "$NEW" "$PREVIOUS"; do
        [[ ! -L $path ]] || die "refusing symbolic-link transaction path: $path"
    done

    ASPM_TARGET="$ETC_ROOT/modprobe.d/99-$PROJECT.conf"
    DISPATCHER_TARGET="$ETC_ROOT/NetworkManager/dispatcher.d/99-$PROJECT"
}

validate_stage() {
    local stage=$1 entry base kernel='' index
    local -a entries=()

    [[ -d $stage && ! -L $stage ]] || die "invalid stage directory: $stage"
    shopt -s dotglob nullglob
    entries=("$stage"/*)
    shopt -u dotglob nullglob
    [[ ${#entries[@]} -eq 6 ]] || die 'stage must contain exactly five modules and .build-info'

    for entry in "${entries[@]}"; do
        base=${entry##*/}
        case $base in
            .build-info|mt76.ko|mt76-connac-lib.ko|mt792x-lib.ko|mt7925-common.ko|mt7925e.ko) ;;
            *) die "unexpected staged file: $base" ;;
        esac
        [[ -f $entry && ! -L $entry && -s $entry ]] || die "invalid staged file: $entry"
    done

    for index in "${!MODULE_FILES[@]}"; do
        [[ -f $stage/${MODULE_FILES[$index]} ]] || die "missing staged module: ${MODULE_FILES[$index]}"
    done
    while IFS= read -r entry; do
        case $entry in
            kernel=*)
                [[ -z $kernel ]] || die 'duplicate kernel metadata'
                kernel=${entry#kernel=}
                ;;
        esac
    done < "$stage/.build-info"
    [[ $kernel == "$KVER" ]] || die "stage metadata does not match $KVER"
}

prepare_settings() {
    local disable_aspm=$1 disable_power_save=$2 iw_quoted resolved=''
    local manage_aspm=$disable_aspm manage_dispatcher=$disable_power_save
    local has_aspm=0 has_dispatcher=0

    [[ ! -e $ASPM_TARGET && ! -L $ASPM_TARGET ]] || has_aspm=1
    [[ ! -e $DISPATCHER_TARGET && ! -L $DISPATCHER_TARGET ]] || has_dispatcher=1
    ((disable_aspm || disable_power_save || has_aspm || has_dispatcher)) || return 0

    [[ $disable_aspm == 0 ]] || mkdir -p "${ASPM_TARGET%/*}"
    [[ $disable_power_save == 0 ]] || mkdir -p "${DISPATCHER_TARGET%/*}"
    SETTINGS_TMP=$(mktemp -d "$ETC_ROOT/.$PROJECT.XXXXXX")
    chmod 700 "$SETTINGS_TMP"

    if ((disable_aspm || has_aspm)); then
        ASPM_EXPECTED="$SETTINGS_TMP/aspm.generated"
        printf '%s\noptions mt7925e disable_aspm=1\n' "$GENERATED" > "$ASPM_EXPECTED"
        chmod 644 "$ASPM_EXPECTED"
    fi

    if ((disable_power_save || has_dispatcher)); then
        if resolved=$(command -v "$IW"); then
            IW=$resolved
        elif ((disable_power_save)); then
            die "required command not found: $IW"
        fi
    fi
    if [[ -n $resolved ]]; then
        DISPATCHER_EXPECTED="$SETTINGS_TMP/dispatcher.generated"
        printf -v iw_quoted '%q' "$IW"
        {
            printf '%s\n' '#!/usr/bin/env bash' "$GENERATED" '' 'set -euo pipefail' ''
            printf '%s\n' 'IFACE=${1-}' 'ACTION=${2-}'
            printf '%s\n' '[[ $ACTION == up ]] || exit 0'
            printf '%s\n' '[[ $IFACE =~ ^[A-Za-z0-9_.:-]+$ && $IFACE != none ]] || exit 0'
            printf '%s\n' '[[ -n ${CONNECTION_UUID-} && ${DEVICE_IFACE-} == "$IFACE" ]] || exit 0'
            printf '%s\n' 'module_path=$(readlink -f -- "/sys/class/net/$IFACE/device/driver/module" 2>/dev/null) || exit 0'
            printf '%s\n' '[[ ${module_path##*/} == mt7925e ]] || exit 0'
            printf 'exec %s dev "$IFACE" set power_save off\n' "$iw_quoted"
        } > "$DISPATCHER_EXPECTED"
        chmod 755 "$DISPATCHER_EXPECTED"
    fi

    if ((has_aspm)); then
        if matches_generated "$ASPM_TARGET" "$ASPM_EXPECTED"; then
            manage_aspm=1
        elif ((disable_aspm)); then
            die "refusing to replace user-owned file: $ASPM_TARGET"
        else
            manage_aspm=0
        fi
    fi
    if ((has_dispatcher)); then
        if matches_generated "$DISPATCHER_TARGET" "$DISPATCHER_EXPECTED"; then
            manage_dispatcher=1
        elif ((disable_power_save)); then
            die "refusing to replace user-owned file: $DISPATCHER_TARGET"
        else
            manage_dispatcher=0
        fi
    fi
    if ((manage_aspm)); then
        [[ -d ${ASPM_TARGET%/*} && ! -L ${ASPM_TARGET%/*} ]] ||
            die 'unsafe modprobe configuration directory'
    fi
    if ((manage_dispatcher)); then
        [[ -d ${DISPATCHER_TARGET%/*} && ! -L ${DISPATCHER_TARGET%/*} ]] ||
            die 'unsafe NetworkManager dispatcher directory'
    fi
    if ((disable_aspm)); then
        ASPM_DESIRED="$SETTINGS_TMP/aspm.new"
        cp "$ASPM_EXPECTED" "$ASPM_DESIRED"
        chmod 644 "$ASPM_DESIRED"
    fi
    if ((disable_power_save)); then
        DISPATCHER_DESIRED="$SETTINGS_TMP/dispatcher.new"
        cp "$DISPATCHER_EXPECTED" "$DISPATCHER_DESIRED"
        chmod 755 "$DISPATCHER_DESIRED"
    fi
}

activate_setting() {
    local target=$1 desired=$2 expected=$3 name=$4

    if [[ -e $target || -L $target ]]; then
        if matches_generated "$target" "$expected"; then
            mv "$target" "$SETTINGS_TMP/$name.previous"
            printf -v "${name}_backed_up" '%s' 1
        elif [[ -n $desired ]]; then
            die "refusing to replace user-owned file: $target"
        else
            return 0
        fi
    fi
    if [[ -n $desired ]]; then
        mv "$desired" "$target"
        printf -v "${name}_installed" '%s' 1
    fi
}

activate_settings() {
    activate_setting "$ASPM_TARGET" "$ASPM_DESIRED" "$ASPM_EXPECTED" aspm
    activate_setting "$DISPATCHER_TARGET" "$DISPATCHER_DESIRED" "$DISPATCHER_EXPECTED" dispatcher
}

copy_overlay() {
    local stage=$1 file

    mkdir -p "$UPDATES"
    [[ ! -e $PREVIOUS ]] || die "stale transaction directory requires revert: $PREVIOUS"
    rm -rf "$NEW"
    mkdir "$NEW"
    for file in "${MODULE_FILES[@]}" .build-info; do
        cp "$stage/$file" "$NEW/$file"
        chmod 644 "$NEW/$file"
    done
}

install_overlay() {
    local stage=$1 disable_aspm=$2 disable_power_save=$3

    [[ $disable_aspm == 0 || $disable_aspm == 1 ]] || die 'DISABLE_ASPM must be 0 or 1'
    [[ $disable_power_save == 0 || $disable_power_save == 1 ]] ||
        die 'DISABLE_POWER_SAVE must be 0 or 1'
    validate_stage "$stage"
    prepare_settings "$disable_aspm" "$disable_power_save"
    copy_overlay "$stage"
    transaction_started=1
    unload_stack

    if [[ -e $ACTIVE ]]; then
        [[ -d $ACTIVE ]] || die "invalid active overlay: $ACTIVE"
        mv "$ACTIVE" "$PREVIOUS"
        previous_moved=1
    fi
    mv "$NEW" "$ACTIVE"
    new_active=1

    "$DEPMOD" -a "$KVER"
    verify_overlay_resolution
    "$MODPROBE" mt7925e
    verify_loaded_stack
    activate_settings

    rm -rf "$PREVIOUS"
    previous_moved=0
    committed=1
    printf 'Installed mt7925 module overlay for %s.\n' "$KVER"
}

revert_overlay() {
    transaction_started=1
    unload_stack
    rm -rf "$NEW" "$PREVIOUS"
    if [[ -e $ACTIVE ]]; then
        [[ -d $ACTIVE ]] || die "invalid active overlay: $ACTIVE"
        mv "$ACTIVE" "$PREVIOUS"
        previous_moved=1
    fi

    prepare_settings 0 0
    activate_settings
    "$DEPMOD" -a "$KVER"
    verify_stock_resolution
    "$MODPROBE" mt7925e
    verify_loaded_stack

    rm -rf "$PREVIOUS"
    previous_moved=0
    committed=1
    printf 'Reverted to stock mt7925 modules for %s.\n' "$KVER"
}

require_safe_roots
resolve_command MODPROBE "$MODPROBE"
resolve_command DEPMOD "$DEPMOD"
resolve_command MODINFO "$MODINFO"

case ${1-} in
    install)
        [[ $# -eq 5 ]] || { usage; exit 2; }
        set_kernel_paths "$3"
        install_overlay "$2" "$4" "$5"
        ;;
    revert)
        [[ $# -eq 2 ]] || { usage; exit 2; }
        set_kernel_paths "$2"
        revert_overlay
        ;;
    *)
        usage
        exit 2
        ;;
esac
